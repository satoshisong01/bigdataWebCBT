// Generates src/data/meta.ts — the light index (id/subject/topics) that analytics use
// so the home page never downloads the full question bank.
// QuestionMeta.subject is the 2027 출제기준 subject of the question's first topic (criteriaSubjectOf in
// src/data/criteria.ts — the same rule composed mock exams use), or the question's own subject when untagged.
// Usage: node scripts/build-meta.mjs   (re-run after any change to src/data/sessions, src/data/concepts or src/data/criteria.ts)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const ts = require(path.join(root, 'node_modules', 'typescript'));

function loadTs(file) {
  const src = fs.readFileSync(file, 'utf8');
  const out = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
  }).outputText;
  const mod = { exports: {} };
  new Function('module', 'exports', 'require', out)(mod, mod.exports, () => ({}));
  return mod.exports;
}

const bankSrc = fs.readFileSync(path.join(root, 'src/data/bank.ts'), 'utf8');
const sessionIds = [...bankSrc.matchAll(/import\('\.\/sessions\/([\w-]+)'\)/g)].map(m => m[1]);

const questions = sessionIds.flatMap(id => loadTs(path.join(root, 'src/data/sessions', `${id}.ts`)).questions);
const cards = [1, 2, 3, 4].flatMap(s => loadTs(path.join(root, 'src/data/concepts', `s${s}.ts`)).cards);
const { criteriaSubjectOf } = loadTs(path.join(root, 'src/data/criteria.ts'));

const qRows = questions.map(q => JSON.stringify([q.id, criteriaSubjectOf(q), q.topics ?? []]));
const cRows = cards.map(c => JSON.stringify([c.id, c.topic, c.importance]));

const out = `// GENERATED by scripts/build-meta.mjs — do not edit by hand.
import type { QuestionMeta, CardMeta, Importance } from '@/types';
import { sessionIdOf } from './catalog';

const Q: ReadonlyArray<[string, number, string[]]> = [
${qRows.join(',\n')}
];

const C: ReadonlyArray<[string, string, Importance]> = [
${cRows.join(',\n')}
];

export const QUESTION_META: readonly QuestionMeta[] = Q.map(([id, subject, topics]) => ({
  id,
  sessionId: sessionIdOf(id),
  subject,
  topics,
}));

export const CARD_META: readonly CardMeta[] = C.map(([id, topic, importance]) => ({ id, topic, importance }));
`;

fs.writeFileSync(path.join(root, 'src/data/meta.ts'), out);
console.log(`meta.ts: ${questions.length} questions, ${cards.length} cards from sessions [${sessionIds.join(', ')}]`);
